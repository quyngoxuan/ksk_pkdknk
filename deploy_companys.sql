GO

SET QUOTED_IDENTIFIER ON;
GO

SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID(N'dbo.Companys', N'U') IS NULL
CREATE TABLE dbo.Companys (
    ID BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_Companys PRIMARY KEY,
    Name NVARCHAR(300) NOT NULL,
    MST VARCHAR(30) NULL,
    [Desc] NVARCHAR(1000) NULL,
    CreatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_Companys_CreatedAt DEFAULT SYSDATETIME(),
    UpdatedAt DATETIME2(0) NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'UX_Companys_MST' AND object_id = OBJECT_ID(N'dbo.Companys'))
CREATE UNIQUE INDEX UX_Companys_MST ON dbo.Companys(MST) WHERE MST IS NOT NULL;
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_Companys_Name' AND object_id = OBJECT_ID(N'dbo.Companys'))
CREATE INDEX IX_Companys_Name ON dbo.Companys(Name);
GO

COMMIT TRANSACTION;
GO

SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = 'dbo' AND TABLE_NAME = 'Companys';
GO
