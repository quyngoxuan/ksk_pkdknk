IF COL_LENGTH(N'dbo.Patients', N'SHS') IS NULL
    ALTER TABLE dbo.Patients ADD SHS VARCHAR(30) NULL;
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_Patients_SHS' AND object_id = OBJECT_ID(N'dbo.Patients'))
    CREATE INDEX IX_Patients_SHS ON dbo.Patients(SHS);
GO

SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'dbo' AND TABLE_NAME = 'Patients' AND COLUMN_NAME = 'SHS';
GO
