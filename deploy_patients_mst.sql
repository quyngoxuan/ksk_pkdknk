IF COL_LENGTH(N'dbo.Patients', N'MST') IS NULL
    ALTER TABLE dbo.Patients ADD MST VARCHAR(30) NULL;
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_Patients_MST' AND object_id = OBJECT_ID(N'dbo.Patients'))
    CREATE INDEX IX_Patients_MST ON dbo.Patients(MST);
GO

SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'dbo' AND TABLE_NAME = 'Patients' AND COLUMN_NAME = 'MST';
GO
